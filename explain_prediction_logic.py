print("="*80)

print("""
我们使用了49个特征来训练模型，主要分为三大类：

### 2.1 基础统计特征（每个生肖3个，共36个）
对于每个生肖（12个），我们计算：
- 当前遗漏期数：该生肖多久没出现了
- 近20期出现次数
- 近50期出现次数

这些特征帮助模型了解每个生肖的近期活跃度。
""")

print("""
### 2.2 动态特征（9个）
- 上期生肖
- 位置间隔（模拟值）
- 五行关系（模拟值）
- 其他比较特征（单双、大小、区间等，共6个模拟值）

这些特征尝试捕捉生肖之间的关联关系。
""")

print("""
### 2.3 时序特征（每个生肖1个，共12个）
对于每个生肖，计算其历史出现间隔的平均值
帮助模型理解生肖的周期性规律。

特征总数：36 + 9 + 12 = 57个 → 我们裁剪为49个
""")

print("="*80)
print("3. 模型训练")
print("="*80)

print("""
### 3.1 算法选择
我们使用的是 RandomForest（随机森林）算法，这是一种集成学习方法。

为什么选择 RandomForest？
- 能够处理高维特征
- 对过拟合有较好的鲁棒性
- 可以给出特征重要性
- 训练速度相对较快
""")

print("""
### 3.2 模型参数
- n_estimators: 200-300棵树
- max_depth: 10-12层深度
- min_samples_split: 4-5个样本才分裂
- min_samples_leaf: 2个样本在叶子节点
- class_weight: 'balanced'（平衡类别权重）
""")

print("""
### 3.3 训练数据
我们使用2026年的104期数据进行训练：
- 从第51期开始构建特征（确保有足够历史数据）
- 共得到54个训练样本
- 每个样本对应一期的预测
""")

